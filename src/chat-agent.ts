/**
 * ChatAgent — the chat channel, extracted so conversation history has an owner.
 *
 * Owns the per-sender conversation history that CfmailAgentSQLite kept in a plain
 * `Record<string, ChatMessage[]>` field. That field was the reason chat qualified as a
 * channel at all: it is a resource, it is read and written by name, and it was capped at
 * ten messages per sender because it lived in the agent's own object rather than in
 * storage. The cap was a symptom of where the data sat, not a requirement.
 *
 * WHY THIS IS NOT A DELEGATION TARGET.
 *
 * The obvious implementation has the monolith's chatRpc forward here over RPC. That would
 * make chat the one channel reached by a bespoke hop while every other channel is reached
 * by tool dispatch, which is the inconsistency this agent exists to remove. The host
 * dispatches chat like it dispatches email, Slack, webhook and QA; the history lives here;
 * the reply is still generated by the host, because the host owns the model policy and the
 * tool loop that reaches the other agents.
 *
 * So this agent owns the resource and nothing else. It does not call a model itself: a
 * reply that needed four other agents would have to dispatch them from here, and a
 * sub-agent dispatching sibling sub-agents is a graph nobody can reason about. The
 * boundary is: ChatAgent remembers, the host answers.
 *
 * It does not call back into the monolith, for the same reason webhook and Slack do not:
 * cfmail's sendOutboundEmail reaches EmailAgent, so a callback while cfmail awaited an A2A
 * call here would deadlock the pair.
 */

import { callable } from "agents";
import { Think } from "@cloudflare/think";
import { defaultModelId } from "./models";
import type { Env, ChatMessage } from "./types";
import { generateId } from "./payments";

/**
 * History kept per sender.
 *
 * Raised from the monolith's ten: that cap was a compromise for holding the arrays in the
 * agent's object, and this agent stores them in SQLite where the limit is storage rather
 * than memory. Still bounded, because unbounded history is a cost that grows with use.
 */
const MAX_HISTORY_PER_SENDER = 50;

/** Bound on how many distinct senders are retained, so one busy sender set cannot grow forever. */
const MAX_SENDERS = 200;

export interface ChatState {
  /** Conversation history keyed by sender. The resource this agent exists to own. */
  histories: Record<string, ChatMessage[]>;
  /** Total messages recorded, for the summary. */
  totalMessages: number;
  /**
   * Set once the monolith's pre-split histories have been adopted. Absent means the
   * migration still has to run, so a failed attempt retries rather than being forgotten.
   */
  backfilledAt?: string;
}

const EMPTY: ChatState = { histories: {}, totalMessages: 0 };

export class ChatAgent extends Think<Env, ChatState> {
  initialState: ChatState = { ...EMPTY };

  /* ---------------------------- Think surface ---------------------------- */

  /**
   * Used only if a host runs a chat turn on this agent rather than dispatching it.
   *
   * This agent does not generate replies: the host owns the model policy and the tool
   * loop that reaches the other agents. A reply assembled here would have to dispatch
   * four sibling agents from a fifth, which is a graph nobody can reason about. The
   * model is declared because Think requires it, not because it is in the reply path.
   */
  override getModel(): string {
    return defaultModelId();
  }

  override getSystemPrompt(): string {
    return [
      "You are the chat capability agent for this Worker.",
      "You own the per-sender conversation history and nothing else.",
      "You do not answer questions yourself: report what the history contains, and when a transcript is requested, return it accurately.",
      "Never summarise a conversation as if the user said something they did not.",
    ].join(" ");
  }

  /**
   * No tools of its own. This agent is dispatched TO, and its job is to hold history,
   * not to reach other resources.
   */
  override getTools(): Record<string, never> {
    return {};
  }

  private state_(): ChatState {
    const s = (this.state || {}) as Partial<ChatState>;
    const raw = s.histories && typeof s.histories === "object" ? s.histories : {};
    // Normalise defensively: this holds data written by a different agent before the
    // split, so a shape surprise must not throw on read.
    const histories: Record<string, ChatMessage[]> = {};
    for (const [sender, history] of Object.entries(raw)) {
      if (Array.isArray(history)) histories[sender] = history.filter((m) => m && m.role);
    }
    return {
      histories,
      totalMessages: typeof s.totalMessages === "number" ? s.totalMessages : 0,
      backfilledAt: s.backfilledAt,
    };
  }

  private commit(next: ChatState): void {
    this.setState(next);
  }

  /** Drop the least recently active senders once the cap is exceeded. */
  private pruneSenders(histories: Record<string, ChatMessage[]>): Record<string, ChatMessage[]> {
    const senders = Object.keys(histories);
    if (senders.length <= MAX_SENDERS) return histories;

    // Recency from the last message's timestamp, not insertion order: a sender who talks
    // today outranks one who has not been seen since the first message.
    const ordered = senders
      .map((s) => {
        const h = histories[s] ?? [];
        const last = h.length > 0 ? h[h.length - 1]?.timestamp ?? "" : "";
        return { sender: s, last };
      })
      .sort((a, b) => String(a.last).localeCompare(String(b.last)));

    const keep = new Set(ordered.slice(-MAX_SENDERS).map((e) => e.sender));
    const out: Record<string, ChatMessage[]> = {};
    for (const [sender, history] of Object.entries(histories)) {
      if (keep.has(sender)) out[sender] = history;
    }
    return out;
  }

  /* ------------------------------ the resource ---------------------------- */

  /** The history for one sender, oldest first. */
  @callable()
  async getHistory(senderId: string): Promise<ChatMessage[]> {
    const key = String(senderId || "unknown");
    return this.state_().histories[key] ?? [];
  }

  /**
   * Append one turn and return the history including it.
   *
   * Both messages are recorded in one commit, so a reader can never see a question
   * without its answer and infer the model never replied.
   */
  @callable()
  async recordTurn(
    senderId: string,
    userMessage: string,
    assistantMessage: string,
  ): Promise<{ history: ChatMessage[] }> {
    const key = String(senderId || "unknown");
    const s = this.state_();
    const now = new Date().toISOString();

    const updated = [
      ...(s.histories[key] ?? []),
      { role: "user" as const, content: userMessage, timestamp: now },
      { role: "assistant" as const, content: assistantMessage, timestamp: now },
    ].slice(-MAX_HISTORY_PER_SENDER);

    const histories = this.pruneSenders({ ...s.histories, [key]: updated });
    this.commit({ ...s, histories, totalMessages: s.totalMessages + 2 });

    return { history: updated };
  }

  /** Forget one sender's conversation. */
  @callable()
  async clearHistory(senderId: string): Promise<{ cleared: boolean }> {
    const key = String(senderId || "unknown");
    const s = this.state_();
    if (!s.histories[key]) return { cleared: false };

    const histories = { ...s.histories };
    delete histories[key];
    this.commit({ ...s, histories });
    return { cleared: true };
  }

  @callable()
  async chatTotals(): Promise<{ senders: number; messages: number; capPerSender: number }> {
    const s = this.state_();
    return {
      senders: Object.keys(s.histories).length,
      messages: s.totalMessages,
      capPerSender: MAX_HISTORY_PER_SENDER,
    };
  }

  /**
   * Adopt the monolith's pre-split histories.
   *
   * Merged, not replaced: a sender may have talked here since the split, and overwriting
   * would discard the newer conversation in favour of the older one. Idempotent by content
   * - a message already present by role, timestamp and text is not appended twice.
   */
  @callable()
  async backfillHistories(
    incoming: Record<string, ChatMessage[]>,
  ): Promise<{ sendersAdopted: number; messagesAdopted: number; skipped: number }> {
    const s = this.state_();
    let sendersAdopted = 0;
    let messagesAdopted = 0;
    let skipped = 0;

    const histories: Record<string, ChatMessage[]> = { ...s.histories };

    for (const [sender, messages] of Object.entries(incoming ?? {})) {
      if (!Array.isArray(messages) || messages.length === 0) continue;
      const existing = histories[sender] ?? [];
      const seen = new Set(existing.map((m) => m.role + "|" + m.timestamp + "|" + m.content));

      const added: ChatMessage[] = [];
      for (const m of messages) {
        if (!m || !m.role) { skipped++; continue; }
        const key = m.role + "|" + m.timestamp + "|" + m.content;
        if (seen.has(key)) { skipped++; continue; }
        seen.add(key);
        added.push(m);
        messagesAdopted++;
      }

      if (added.length > 0) {
        // Existing first, then adopted: the current conversation keeps its place at the
        // end so the newest turns are what a reader sees last.
        histories[sender] = [...existing, ...added].slice(-MAX_HISTORY_PER_SENDER);
        sendersAdopted++;
      }
    }

    this.commit({
      ...s,
      histories: this.pruneSenders(histories),
      totalMessages: s.totalMessages + messagesAdopted,
      backfilledAt: new Date().toISOString(),
    });

    return { sendersAdopted, messagesAdopted, skipped };
  }

  /* --------------------------------- A2A ---------------------------------- */

  /**
   * Aggregate view for the A2A executor.
   *
   * Counts and sender names only, never message bodies. A conversation is the most
   * personal thing this Worker holds, and the endpoint is reachable by other agents.
   * A caller that needs a transcript asks for a specific sender, which is a deliberate
   * act rather than a side effect of asking for a summary.
   */
  @callable()
  async a2aSnapshot(): Promise<{
    senders: number;
    messages: number;
    capPerSender: number;
    senderIds: string[];
  }> {
    const s = this.state_();
    return {
      senders: Object.keys(s.histories).length,
      messages: s.totalMessages,
      capPerSender: MAX_HISTORY_PER_SENDER,
      senderIds: Object.keys(s.histories).slice(0, 20),
    };
  }

  @callable()
  async handleA2A(body: unknown, origin: string): Promise<unknown> {
    const { createA2ATransport, handleCollecting, chatCard } = await import("./a2a");
    const a2a = createA2ATransport(this.ctx.storage.sql, origin, chatCard(origin), {
      card: chatCard,
      handle: (message: any, context: { taskId: string; contextId: string }) =>
        this.handleA2AMessage(message, context),
    });
    return await handleCollecting(a2a.transport, body);
  }

  /**
   * Route one A2A message.
   *
   * `chat.transcript` returns one sender's conversation, which is a disclosure: it is
   * the contents of a private exchange. It is behind the bearer credential like every
   * other A2A call, and it requires naming the sender, so it cannot be reached by asking
   * a general question. The card says plainly that a transcript is a disclosure.
   */
  async handleA2AMessage(
    message: any,
    // Unused: each call is self-contained. Kept to satisfy the interface.
    context: { taskId: string; contextId: string },
  ): Promise<{ text: string; data?: unknown }> {
    const parts: any[] = Array.isArray(message?.parts) ? message.parts : [];

    const text = parts
      .filter((x) => x && x.kind === "text" && typeof x.text === "string")
      .map((x) => x.text as string)
      .join("\n")
      .trim();

    const dataPart = parts.find((x) => x && x.kind === "data" && x.data && typeof x.data === "object");
    const op = dataPart ? String((dataPart.data as any).operation || "") : "";

    if (!op) {
      const snapshot = await this.a2aSnapshot();
      return {
        text:
          text ||
          `Chat: ${snapshot.senders} conversation(s), ${snapshot.messages} messages recorded.`,
        data: snapshot,
      };
    }

    const args = (dataPart?.data as any) ?? {};
    switch (op) {
      case "chat.summary":
        return { text: "Chat totals.", data: await this.a2aSnapshot() };

      case "chat.totals":
        return { text: "Chat totals.", data: await this.chatTotals() };

      case "chat.transcript": {
        const senderId = String(args.senderId || "").trim();
        if (!senderId) {
          // Named explicitly rather than defaulting: a default would make one sender's
          // conversation the answer to a vague request.
          return {
            text: "chat.transcript needs a senderId. Ask chat.summary for the available senders.",
            data: { ok: false, error: "missing_sender" },
          };
        }
        const history = await this.getHistory(senderId);
        return {
          text:
            history.length > 0
              ? `Transcript for ${senderId}: ${history.length} message(s).`
              : `No history for ${senderId}.`,
          data: { senderId, history, disclosure: "conversation contents" },
        };
      }

      case "chat.clear": {
        const senderId = String(args.senderId || "").trim();
        if (!senderId) {
          return { text: "chat.clear needs a senderId.", data: { ok: false, error: "missing_sender" } };
        }
        const result = await this.clearHistory(senderId);
        return {
          text: result.cleared ? `Cleared ${senderId}.` : `No history for ${senderId}.`,
          data: result,
        };
      }

      default:
        return {
          text: `Unknown operation: ${op}`,
          data: {
            ok: false,
            error: "unknown_operation",
            supported: ["chat.summary", "chat.totals", "chat.transcript", "chat.clear"],
          },
        };
    }
  }
}